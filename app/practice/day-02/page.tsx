export default function Day02Page() {
  return (
    <>
      <h1>自己紹介</h1>
      <p>
        こんにちは、<span>若杉</span>です。
      </p>

      <h2>確認クイズ</h2>
      <p>
        下のリストは、本来はタグの意味に合わせて書くべきところを、
        すべて&lt;div&gt;で済ませてしまった「良くない例」です。
        それぞれ意味に合った適切なタグに直してみましょう。
      </p>
      <pre>
        <code>{`// 良くない例（全部divで書いてしまっている）
<div>段落</div>
<div>大見出し</div>
<div>中見出し</div>
<div>太字・強調したい部分</div>
<div>斜体で表したい部分</div>
<div>リンクにしたい文字列</div>
<div>引用文</div>
<div>コード（等幅フォント）で表したい部分</div>
<div>ページのヘッダー部分</div>
<div>ナビゲーションメニュー</div>
<div>独立した内容のまとまり（記事など）</div>
<div>ページのフッター部分</div>
<div>ボタンとして表示したい文字</div>
<div>意味を持たない箱（ブロック要素をまとめたいだけ）</div>
<div>意味を持たない範囲（インライン要素をまとめたいだけ）</div>`}</code>
      </pre>

      <p>適切なタグに直すとこうなります。</p>

      {/* 段落 → p（ふつうの文章） */}
      <p>段落</p>

      {/* 大見出し → h1（ページの中で一番大きな見出し） */}
      <h1>大見出し</h1>

      {/* 中見出し → h2（h1の次に大きい見出し） */}
      <h2>中見出し</h2>

      {/* 太字・強調 → strong（インライン要素なので、pなどの中で使う） */}
      <p>
        <strong>太字・強調したい部分</strong>
      </p>

      {/* 斜体・強調 → em（インライン要素） */}
      <p>
        <em>斜体で表したい部分</em>
      </p>

      {/* リンク → a（インライン要素） */}
      <p>
        <a href="#">リンクにしたい文字列</a>
      </p>

      {/* 引用文 → blockquote（ブロック要素） */}
      <blockquote>引用文</blockquote>

      {/* コード（等幅フォント） → code（インライン要素） */}
      <p>
        <code>コード（等幅フォント）で表したい部分</code>
      </p>

      {/* ページのヘッダー部分 → header（意味を持つブロック要素） */}
      <header>ページのヘッダー部分</header>

      {/* ナビゲーションメニュー → nav（意味を持つブロック要素） */}
      <nav>ナビゲーションメニュー</nav>

      {/* 独立した内容のまとまり → section（意味を持つブロック要素） */}
      <section>独立した内容のまとまり（記事など）</section>

      {/* ページのフッター部分 → footer（意味を持つブロック要素） */}
      <footer>ページのフッター部分</footer>

      {/* ボタン → button */}
      <button>ボタンとして表示したい文字</button>

      {/*
        意味を持たない「箱」をまとめたいだけのときは、
        無理に意味のあるタグを探さず、divのままでOK（ブロック要素）
      */}
      <div>意味を持たない箱（ブロック要素をまとめたいだけ）</div>

      {/*
        意味を持たない「範囲」を文章の中でまとめたいだけのときは、
        spanを使う（インライン要素なので、pなどの中で使う）
      */}
      <p>
        <span>意味を持たない範囲（インライン要素をまとめたいだけ）</span>
      </p>
    </>
  );
}
